export const LANGUAGES = { en, ru } as const;
export type Lang = keyof typeof LANGUAGES;

let current: Lang = "en";

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return current;
}

export function detectLang(): Lang {
  const preferred = navigator.language.slice(0, 2).toLowerCase();
  return preferred in LANGUAGES ? (preferred as Lang) : "en";
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const template = LANGUAGES[current][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** For dynamic keys such as `cat.${category}`. */
export function tk(key: string, vars?: Record<string, string | number>): string {
  return key in en ? t(key as Key, vars) : key;
}
